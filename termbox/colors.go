// OutputMode represents an output mode, which determines how colors
// are used.
type OutputMode int

// OutputMode values.  OutputNormal clamps palette indices to 16 colors;
// Output256 (the default) passes indices 0-255 through.  Output216 and
// OutputGrayscale are retained for API compatibility and behave as
// pass-through.
const (
	OutputCurrent OutputMode = iota
	OutputNormal
	Output256
	Output216
	OutputGrayscale
)

// InputMode is retained for compatibility; only InputMouse has effect.
type InputMode int

const (
	InputEsc InputMode = 1 << iota
	InputAlt
	InputMouse
	InputCurrent InputMode = 0
)
